/** Human-readable audit action; falls back to the raw `action` when unmapped (H3 slice). */
export function publicAuditActionLabel(locale: PublicLocale, action: string): string {
  const k = `desk.audit.action.${action}`;
  const loc = publicMessages[locale] as Record<string, string>;
  const en = publicMessages.en as Record<string, string>;
  const label = loc[k] ?? en[k];
  return typeof label === 'string' ? label : action;
}

export type PublicMessageKey = keyof typeof publicMessages.en;

export function publicT(locale: PublicLocale, key: PublicMessageKey): string {
  const table = publicMessages[locale];
  const v = table[key];
  return (v ?? publicMessages.en[key]) as string;
}
